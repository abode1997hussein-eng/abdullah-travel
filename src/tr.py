MISSING = set()


def T(s, lang):
    """ترجمة نص واحد. العربي يرجع مثل ما هو."""
    if lang == "ar" or not s:
        return s
    i = 0 if lang == "en" else 1
    s0 = s.strip()
    if s0 in D:
        return D[s0][i]
    for pat, en, ku in PATTERNS:
        m = re.match(pat, s0)
        if m:
            return (en, ku)[i].format(*[g.replace(" ", "") for g in m.groups()])
    # نص بدون أي حرف عربي (أسعار، أسماء إنكليزية) يبقى مثل ما هو
    if not re.search(r"[\u0600-\u06FF]", s0):
        return s0
    # «اليوم التاريخ (ملاحظة)»
    m = re.match(r"^(?:(\S+) )?(\d{2}-\d{2}-\d{4})(?: \((.+)\))?$", s0)
    if m and (m.group(1) is None or m.group(1) in DAYS):
        out = (DAYS[m.group(1)][i] + " " if m.group(1) else "") + m.group(2)
        return out + (" (" + T(m.group(3), lang) + ")" if m.group(3) else "")
    # «عربي · عربي» يترجم كل جزء لحاله
    if " · " in s0:
        return " · ".join(T(x, lang) for x in s0.split(" · "))
    # اسم فندق «عربي (English)»: الإنكليزي ياخذ الاسم اللاتيني، والكوردي يبقى مثل ما هو
    m = re.match(r"^(.+?) \(([^)]*[A-Za-z][^)]*)\)$", s0)
    if m:
        return m.group(2) if lang == "en" else s0
    MISSING.add(s0)
    return s
