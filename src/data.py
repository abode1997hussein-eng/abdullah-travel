def g(**kw):
    row = {h: "" for h in G_HEAD}
    row["ظاهر"] = "نعم"
    row.update(kw)
    return row


GROUPS = []


def trip(head, keys, rows):
    """كروب واحد: head معلومات الكروب، وكل سطر بـ rows خيار (فندق/مدة) بأعمدة keys.
    الخلية الفاضية بعمود البرنامج أو الفندق تاخذ قيمة السطر اللي قبلها."""
    prev = {}
    for i, r in enumerate(rows):
        row = dict(zip(keys, r))
        for k in ("البرنامج", "الفندق"):
            if k in row and row[k] == "" and k in prev:
                row[k] = prev[k]
        prev = row
        base = dict(head) if i == 0 else {"الوجهة": head["الوجهة"]}
        base.update(row)
        GROUPS.append(g(**base))


def usd(*ps):
    return tuple(p if p == "" or not isinstance(p, (int, float)) else "%d$" % p for p in ps)


